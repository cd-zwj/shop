package com.payment.enums;

/**
 * 支付状态枚举。
 *
 * 描述支付账单从发起到完成（或失败/关闭）的流转状态，
 * 用于跟踪第三方支付渠道的回调结果。
 */
public enum PayStatusEnum {
    /** 待支付：支付账单已创建，等待用户发起支付 */
    WAIT_PAY,
    /** 支付中：已调用第三方支付渠道，等待回调结果 */
    PAYING,
    /** 支付成功：收到第三方支付渠道的成功回调 */
    SUCCESS,
    /** 支付失败：第三方支付渠道返回失败或异常 */
    FAILED,
    /** 已关闭：支付超时或被主动关闭 */
    CLOSED
}
